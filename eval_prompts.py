def get_prompts(dialect: str = 'saudi'):
    d = dialect.lower()
    if d in ['saudi', 'ar-sa', 'sa']:
        return SAUDI_PROMPTS
    elif d in ['emirati', 'uae', 'ar-ae', 'ae']:
        return EMIRATI_PROMPTS
    raise ValueError(f'Unknown dialect: {dialect}')
